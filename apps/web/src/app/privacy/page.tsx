      <p>웹 사용 통계의 국외 이전은 아래 8절의 방법으로 거부할 수 있습니다. 앱 사용 통계의 국외 이전은 앱의 설정 &gt; 개인정보에서 &ldquo;사용 통계 보내기&rdquo;를 꺼서 거부할 수 있으며, 꺼도 서비스 이용에는 제한이 없습니다. 푸시 알림의 국외 이전은 앱의 &ldquo;새 모집 알림&rdquo;을 끄거나 로그아웃하면 멈추며(기기 토큰을 지웁니다), 이 경우 푸시 알림만 받을 수 없습니다. 광고의 국외 이전은 광고 선택 동의를 하지 않거나 설정 &gt; 개인정보의 &ldquo;광고 목적 정보 제공&rdquo;을 꺼서 거부할 수 있으며, 이 경우 광고만 표시되지 않습니다. 이메일 인증번호 메일의 국외 이전은 사용자가 &ldquo;인증번호 받기&rdquo;를 눌렀을 때만 일어나며, 인증은 선택이라 요청하지 않으면 전송되지 않고 연락처는 인증 표시 없이 그대로 쓸 수 있습니다.</p>
